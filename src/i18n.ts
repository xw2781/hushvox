const dicts: Record<Lang, Dict> = { en: en as Dict, zh, ja, ko };

// ---- state --------------------------------------------------------------------------------
export const STORAGE_KEY = 'hushvox-lang';
let current: Lang = 'en';
const listeners = new Set<(l: Lang) => void>();

export const getLang = () => current;
export const onLangChange = (cb: (l: Lang) => void) => { listeners.add(cb); };

/** Accepts en, zh, zh-CN, zh-Hans, ja-JP, ko-KR, ... (case-insensitive, `_` or `-`). */
export function parseLang(v: string | null | undefined): Lang | null {
  const p = (v ?? '').trim().toLowerCase().replace('_', '-').split('-')[0];
  return p === 'en' || p === 'zh' || p === 'ja' || p === 'ko' ? p : null;
}

function readStored(): Lang | null {
  try { return parseLang(localStorage.getItem(STORAGE_KEY)); } catch { return null; }
}

/** ?lang= > localStorage > navigator.languages > English. */
export function resolveLang(): Lang {
  const fromUrl = parseLang(new URLSearchParams(location.search).get('lang'));
  if (fromUrl) return fromUrl;
  const stored = readStored();
  if (stored) return stored;
  for (const l of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const m = parseLang(l);
    if (m) return m;
  }
  return 'en';
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  const s = dicts[current][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s;
}

const tk = (key: string) => t(key as MsgKey);

export function applyTranslations(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((e) => { e.textContent = tk(e.dataset.i18n!); });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((e) => { e.innerHTML = tk(e.dataset.i18nHtml!); });
  root.querySelectorAll<HTMLElement>('[data-i18n-attr]').forEach((e) => {
    for (const pair of e.dataset.i18nAttr!.split(';')) {
      const [attr, key] = pair.split(':').map((x) => x.trim());
      if (attr && key) e.setAttribute(attr, tk(key));
    }
  });
}

/** Applies `lang` to the document (without persisting). Notifies listeners so dynamic views re-render. */
export function setLang(lang: Lang) {
  current = lang;
  document.documentElement.lang = LANGS.find((l) => l.id === lang)!.htmlLang;
  applyTranslations();
  listeners.forEach((cb) => cb(lang));
}

/** An explicit user choice: apply, remember, and mirror into the URL (other params and the hash are kept). */
export function chooseLang(lang: Lang) {
  setLang(lang);
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage unavailable */ }
  const url = new URL(location.href);
  url.searchParams.set('lang', lang);
  history.replaceState(history.state, '', url);
}
